// Generates a CycloneDX 1.5 SBOM for the release: web-dist/sbom.cdx.json.
// Plain Node, no dependencies. Reads package.json + package-lock.json, lists the
// dependency tree (runtime and dev) and the vendored components, and stamps the
// app version. Run after build:web: `node build/sbom.js`.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

// First-party components that are not npm packages but are shipped artifacts
// worth tracking in the bill of materials. Keep in sync with the build.
const VENDORED = [
  { type: 'framework', name: 'photoset-engine', version: pkg.version, description: 'The develop pipeline: crop, grade, frames (src/renderer/engine.js).' },
  { type: 'library', name: 'photoset-qr', version: pkg.version, description: 'Hand-rolled QR encoder (src/renderer/qr.js), verified against nayuki reference.' },
  { type: 'library', name: 'photoset-exif', version: pkg.version, description: 'Hand-rolled EXIF writer/reader (src/renderer/exif.js).' },
  { type: 'library', name: 'photoset-zip', version: pkg.version, description: 'Hand-rolled stored ZIP writer (src/renderer/web-api.js makeZip).' },
];

const components = [];
for (const [key, entry] of Object.entries(lock.packages || {})) {
  if (!key.startsWith('node_modules/')) continue;
  const name = key.slice('node_modules/'.length);
  if (name.includes('node_modules/')) continue; // nested transitive copies: list the top-level package only
  const purl = `pkg:npm/${name}@${entry.version}`;
  const comp = {
    type: 'library',
    'bom-ref': purl,
    name,
    version: entry.version,
    purl,
    scope: (pkg.devDependencies && pkg.devDependencies[name]) ? 'excluded' : 'required',
    description: entry.description || undefined,
  };
  if (entry.license) comp.licenses = [{ license: { id: entry.license } }];
  components.push(comp);
}
for (const v of VENDORED) {
  components.push({
    type: v.type,
    'bom-ref': `pkg:generic/photoset/${v.name}@${v.version}`,
    name: v.name,
    version: v.version,
    description: v.description,
  });
}

const bom = {
  bomFormat: 'CycloneDX',
  specVersion: '1.5',
  serialNumber: `urn:uuid:${crypto.randomUUID()}`,
  version: 1,
  metadata: {
    timestamp: new Date().toISOString(),
    component: { type: 'application', 'bom-ref': `pkg:generic/photoset-darkroom@${pkg.version}`, name: 'Photoset Darkroom', version: pkg.version },
    properties: [
      { name: 'photoset:release', value: 'Every release tag carries this SBOM, regenerated by the deploy build.' },
      { name: 'photoset:privacy', value: 'No runtime network dependencies beyond self-hosted assets; RAW decode is on-device (ADR 0004).' },
    ],
  },
  components,
};

const out = path.join(root, 'web-dist', 'sbom.cdx.json');
if (!fs.existsSync(path.join(root, 'web-dist'))) {
  console.error('web-dist/ missing: run `npm run build:web` first');
  process.exit(1);
}
fs.writeFileSync(out, JSON.stringify(bom, null, 2) + '\n');
console.log(`sbom written (${components.length} components) -> web-dist/sbom.cdx.json`);
